#!/usr/bin/env bash
# CDDA 0.I ブラウザ版: ビルドを並列ジョブに分割するための計画を作る
#
# ------------------------------------------------------------------
# なぜ分割するのか
# ------------------------------------------------------------------
# ワークフローが 4 時間かかっていた。内訳は大きく 2 つ:
#
#   (1) コンパイル段: 440 個の翻訳単位（TU）を .o にする
#       → TU 間に依存がないので【いくらでも並列化できる】
#   (2) リンク段: 440 個の .o を wasm にまとめ、
#       Binaryen/wasm-opt が -Os でモジュール全体を最適化する
#       → 単一プロセス・単一スレッドで、【分割できない】
#
# ubuntu-latest は 4 vCPU しかないので、1 ジョブでは make -j4 が上限。
# しかし GitHub Actions は【ジョブを並列に走らせられる】ので、
# 440 個の TU を N 個のジョブに分けて配れば
# 実質 4×N 並列になり、コンパイル段が N 分の 1 に縮む。
#
# リンク段は分割できないので、そこは縮まない。
# つまり理論上の下限は「リンク段の時間」である。
# これは技術的な限界であり、それ以上は縮められない。
#
# ------------------------------------------------------------------
# 分割の正しさをどう担保するか
# ------------------------------------------------------------------
# オブジェクト一覧を ls src/*.cpp などで【推測してはいけない】。
# CDDA の Makefile は
#     SOURCES += $(THIRD_PARTY_SOURCES)   (flatbuffers / zstd)
#     SOURCES += $(IMGUI_SOURCES)         (SDL の有無で中身が変わる)
# のように条件分岐でソースを増減させるので、推測すると取りこぼして
# リンク時に未定義シンボルになる。
#
# そこで tune-makefile.sh が追加した print-OBJS ターゲットで
# 【Makefile 自身に聞く】。これが唯一正しい一覧である。
#
# ------------------------------------------------------------------
# 使い方
# ------------------------------------------------------------------
#   cdda のチェックアウト先で
#       ../ci/shard-plan.sh <シャード数> [出力先ディレクトリ]
#
#   出力:
#     <出力先>/objs-all.txt        全オブジェクトの一覧（1 行 1 個）
#     <出力先>/shard-<i>.txt       シャード i が作るオブジェクトの一覧
#     <出力先>/matrix.json         Actions の matrix に渡す JSON 配列
#     <出力先>/summary.txt         人が読む要約
set -euo pipefail

SHARDS="${1:-6}"
OUT_DIR="${2:-../shard-plan}"

if ! [ "$SHARDS" -ge 1 ] 2>/dev/null; then
    echo "ERROR: シャード数は 1 以上の整数で指定してください（受け取った値: $SHARDS）" >&2
    exit 1
fi

if [ ! -f Makefile ]; then
    echo "ERROR: CDDA のソースツリー内で実行してください" >&2
    exit 1
fi

if ! grep -q '^print-%:' Makefile; then
    echo "ERROR: Makefile に print-%% ターゲットがありません。" >&2
    echo "       先に ci/tune-makefile.sh を実行してください。" >&2
    exit 1
fi

mkdir -p "$OUT_DIR"

# ------------------------------------------------------------------
# 【重要】前回の shard-*.txt を必ず消す
# ------------------------------------------------------------------
# awk は print > file で追記モードになるうえ、そもそも
# シャード数を減らして再実行すると（例: 6 → 3）
# 前回の shard-3/4/5.txt が残る。すると後段の
#     cat shard-*.txt | sort | uniq -d
# が「前回の割り当て」と「今回の割り当て」を両方拾い、
# 存在しない重複を報告して誤って失敗する。
#
# 実際にこの検証はテスト中にその事故を検出した。
# 出力ディレクトリは使い回される前提なので、
# 生成前に必ず掃除する。
rm -f "$OUT_DIR"/shard-*.txt \
      "$OUT_DIR/objs-all.txt" \
      "$OUT_DIR/objs-reassembled.txt" \
      "$OUT_DIR/matrix.json" \
      "$OUT_DIR/summary.txt"

# ------------------------------------------------------------------
# Makefile にオブジェクト一覧を聞く
# ------------------------------------------------------------------
# 【重要】ここで渡す変数は、実際のビルド・リンクと【完全に同一】で
# なければならない。1 つ違えば OBJS の中身が変わり、
# 「シャードが作った .o」と「リンクが要求する .o」がずれる。
# そのため make の引数は ci/make-args.sh に一元化してある。
# shellcheck source=./make-args.sh
. "$( dirname "$0" )/make-args.sh"

make -s print-OBJS "${CDDA_MAKE_ARGS[@]}" \
    | tr ' ' '\n' | sed '/^$/d' | sort -u > "$OUT_DIR/objs-all.txt"

total="$( wc -l < "$OUT_DIR/objs-all.txt" )"
if [ "$total" -lt 100 ]; then
    echo "ERROR: オブジェクト一覧が ${total} 件しかありません。" >&2
    echo "       CDDA 0.I は 400 件超あるはずなので、make の引数か" >&2
    echo "       print-OBJS ターゲットが壊れている可能性があります。" >&2
    exit 1
fi

# ------------------------------------------------------------------
# シャードへの割り当て
# ------------------------------------------------------------------
# 【割り当て方式】行番号の剰余で配る（ラウンドロビン）。
#
# なぜ「連続ブロック」ではなく剰余なのか:
# 一覧は sort 済みなので、連続ブロックで切ると
# 同じ接頭辞のファイル（例: mapgen*.cpp, monster*.cpp）が
# 1 つのシャードに集まる。CDDA では大きい TU 同士が名前で
# 隣接しがちなので、シャードごとの所要時間が偏る。
# 並列ビルドの所要時間は【最も遅いシャード】で決まるため、
# 偏りはそのまま損失になる。
#
# 剰余で配れば大きい TU が全シャードに散るので、
# 各シャードの合計コンパイル時間がほぼ揃う。
awk -v n="$SHARDS" -v dir="$OUT_DIR" '
{
    idx = ( NR - 1 ) % n;
    print $0 > ( dir "/shard-" idx ".txt" );
}
' "$OUT_DIR/objs-all.txt"

# ------------------------------------------------------------------
# 割り当ての検証
# ------------------------------------------------------------------
# 【必須】シャードの和集合が元の一覧と完全一致すること。
# 取りこぼしがあればリンクで未定義シンボルになり、
# 4 時間待ってから失敗するという最悪の事故になる。
# ここで数秒で検出する。
cat "$OUT_DIR"/shard-*.txt | sort -u > "$OUT_DIR/objs-reassembled.txt"
if ! cmp -s "$OUT_DIR/objs-all.txt" "$OUT_DIR/objs-reassembled.txt"; then
    echo "ERROR: シャードの和集合が元のオブジェクト一覧と一致しません。" >&2
    diff "$OUT_DIR/objs-all.txt" "$OUT_DIR/objs-reassembled.txt" | head -20 >&2
    exit 1
fi

# 重複がないこと（重複すると同じ .o を 2 ジョブが作り、
# アーティファクト展開時に衝突する）。
dup="$( cat "$OUT_DIR"/shard-*.txt | sort | uniq -d | head -5 )"
if [ -n "$dup" ]; then
    echo "ERROR: シャード間で重複しているオブジェクトがあります:" >&2
    echo "$dup" >&2
    exit 1
fi

# ------------------------------------------------------------------
# Actions の matrix 用 JSON
# ------------------------------------------------------------------
# ["0","1",...,"N-1"] の形。fromJSON() で matrix に渡す。
{
    printf '['
    i=0
    while [ "$i" -lt "$SHARDS" ]; do
        [ "$i" -gt 0 ] && printf ','
        printf '"%d"' "$i"
        i=$(( i + 1 ))
    done
    printf ']\n'
} > "$OUT_DIR/matrix.json"

# ------------------------------------------------------------------
# 要約
# ------------------------------------------------------------------
{
    echo "オブジェクト総数: $total"
    echo "シャード数:       $SHARDS"
    echo "1 シャードあたり: 約 $(( total / SHARDS )) 個"
    echo ""
    echo "シャードごとの件数:"
    i=0
    while [ "$i" -lt "$SHARDS" ]; do
        printf '  shard-%-3d %5d 個\n' "$i" "$( wc -l < "$OUT_DIR/shard-$i.txt" )"
        i=$(( i + 1 ))
    done
} > "$OUT_DIR/summary.txt"

cat "$OUT_DIR/summary.txt"
echo ""
echo "[SHARD] OK: 和集合が元の一覧と一致、重複なし"
