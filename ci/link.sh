#!/usr/bin/env bash
# CDDA 0.I ブラウザ版: 全シャードの .o を集めて wasm にリンクする
#
# ==================================================================
# このスクリプトの立ち位置
# ==================================================================
#   plan ジョブ    : ci/shard-plan.sh で 440 個を N 分割
#   compile ジョブ : ci/build-shard.sh を N 並列で実行
#   link ジョブ    : このスクリプト  ← ここ
#
# ==================================================================
# リンク段に何秒かかっているのか（実測。以前の記述は誤りだった）
# ==================================================================
# emcc のリンクは 2 段構えである:
#
#   (1) wasm-ld による通常のリンク（シンボル解決）
#   (2) Binaryen（wasm-opt）による wasm モジュール全体の最適化
#
# 【実測 1: 時間はどこに消えているか】
# 成功実行 33730439512（合計 4h23m）のログから ps を 2218 回
# サンプリングして集計した:
#
#     wasm-opt : 4h02m  ← 全体の【93%】
#     clang    : 約 15m
#     node     : 数分
#
# つまり「4 時間問題」は実質 wasm-opt 1 プロセスの問題である。
#
# 【実測 2: 並列化・増設は効かない】
#     CPU%  平均 105 / 最大 112 / 最小 103  → 4 コア中【1.05 コア】
#     RSS   最大 6.46GB / 16GB              → メモリは余っている
#     起動回数 1                            → 分割の余地なし
# よってランナーのコア増設・メモリ増設・多重起動はいずれも無効。
#
# 【実測 3: 遅いパスは Asyncify ではなかった】
# このファイルは以前「Asyncify の大域解析が支配的で原理的に
# 縮まない」と書いていたが、これは【誤り】だった。
# BINARYEN_PASS_DEBUG=1 でパス別に測ると:
#
#     inlining-optimizing : 71%   ← 真の支配要因
#     asyncify            : 16%
#     その他 31 パス      : 13%
#
# 支配要因がインライン展開なので、最適化レベルを下げれば
# リンク段は実際に縮む。本番と同じ引数で測った結果:
#
#     -Os（従来）: 基準      サイズ 基準
#     -O2        : 【-20%】  サイズ +2.7%
#     -O1        : 【-78%】  サイズ +2.6%
#
# 【運用】ci/tune-makefile.sh が環境変数 CDDA_LINK_OPT で
# この値を切り替える。O2 = 配信用（既定）/ O1 = 検証用。
#
# 【実測 4: 効いたのは版の差し替えだった（F-26）】
# 上の「最適化レベルを下げる」より大きな効果が別にあった。
# inlining-optimizing は、我々の版（Binaryen 116 / 2023年12月）の
# 直後に上流で高速化されていた（2024年9月 PR #6966 / #6967）。
# wasm-opt を版 132 に差し替えるだけで:
#
#     116 -Os 平均 5.871s → 132 -O2 平均 3.650s = 【-37.8%】
#     出力サイズは +0.14% しか増えない
#
# → リンク段 242 分が【約 148 分】になる見込み。
#   差し替えは ci/setup-binaryen.sh が行う（失敗しても 116 で続行）。
#
# 【重要】版 132 に -Os / -O3 / -Oz を使ってはいけない。
# ビルドは成功するのに実行時に LinkError で落ちる。
# ci/tune-makefile.sh が入口で拒否している。
#
# 根拠ログ:
#   docs/measurements/raw/2026-09-04-link-breakdown-real.log
#   docs/measurements/raw/2026-09-04-wasm-opt-scaling.log
#   docs/measurements/raw/2026-09-04-wasm-opt-binaryen-version.log
#
# 【残る下限】
# 並列化できるのはコンパイル段だけであり、全体は
# 「リンク段 + アーティファクト転送 + α」が下限である。
# ただしその「リンク段」自体は上記のとおり可変であって、
# 固定の技術的下限ではない。
#
# ==================================================================
# 【最重要】復元した .o のタイムスタンプ問題
# ==================================================================
# ここが分割ビルドで最も事故りやすい箇所である。
#
# Makefile の規則は
#     $(ODIR)/%.o: $(SRC_DIR)/%.cpp $(PCH_P)
#     $(TARGET): $(OBJS)
# であり、make は【mtime を比較して】再ビルドを判断する。
#
# アーティファクトから .o を復元すると、その mtime は
# 「展開した時刻」ではなく実装依存であり、
# しかも同じジョブで checkout した .cpp の mtime は
# 「checkout した時刻」＝ほぼ現在時刻になる。
#
# つまり高い確率で【.cpp が .o より新しい】と判定され、
# make は 440 個を全部コンパイルし直そうとする。
# そうなると分割した意味が完全に消え、
# しかも「なぜか遅いだけで成功する」ので気づきにくい。
#
# 【対策】リンク前に .o と PCH の mtime を明示的に
# 「今」に更新し、ソースより新しい状態を作る。
#
# これは一見乱暴だが、正当性は担保されている:
#   ・全シャードは同一コミット・同一パッチ・同一 make 変数で
#     コンパイルしている（apply-patches.sh / make-args.sh で強制）
#   ・したがって復元した .o は、そのソースから作られた
#     正しい成果物であることが保証されている
#   ・実在検証（後述）で 440 個すべての存在を確認している
#
# touch の順序も重要である。PCH → .o の順に新しくする必要がある
# （.o は PCH に依存しているため、PCH が .o より新しいと
# やはり再コンパイル対象になる）。
#
# ==================================================================
# 【重要】.d（依存ファイル）が再コンパイルを引き起こす問題
# ==================================================================
# 上の touch だけでは足りなかった。実際に run 33888888789 で
# 【440 個中 406 個が再コンパイルされた】。
#
# 【症状】
# タイムスタンプ整合を済ませた直後にもかかわらず、
#     WARNING: 標本 5 個のうち 5 個が「再ビルド必要」と判定されました
# が出て、リンク段の冒頭 19 分が再コンパイルに費やされた。
#
# 【なぜ 406 個で、440 個ではないのか】
# 再コンパイルされなかった 34 個はすべて src/third-party/ のもの。
# Makefile の規則を見ると差は明白である:
#     $(ODIR)/third-party/%.o: $(SRC_DIR)/third-party/%.cpp   ← PCH に依存しない
#     $(ODIR)/%.o:             $(SRC_DIR)/%.cpp $(PCH_P)      ← PCH に依存する
#
# 【引き金は 2 つあり、どちらも同じ 406 個を指す】
# 最小再現（/tmp で make を使って確認）で、次の 2 つが
# 【それぞれ単独でも】再コンパイルを起こすことを確かめた:
#   機構A: PCH の .d が壊れている → PCH が作り直される
#          → PCH に依存する src/*.o 406 個が巻き添え
#   機構B: 各 .o 自身の .d が壊れている → その .o が直接古いと判定される
# 本番ではこの両方が同時に成立していた。
# したがって「PCH だけ直せばよい」と考えるのは誤りで、
# 【すべての .d を消す】必要がある。
#
# 【406 対 34 の内訳を確実に説明できるのは機構Aのほうである】
# 機構A（PCH 依存）は Makefile の規則から演繹でき、
# 「PCH に依存する 406 個」と「依存しない 34 個」に正確に一致する。
#
# 機構Bが third-party に及ばなかった理由は、確証を取れていない。
# 当初「zstd / imgui は SDL を include しないから」と書いたが、
# これは誤りだった（imgui.cpp は SDL を参照する）。
# 実際の .d を突き合わせれば確定できるはずだが、
# 打ち切られた実行のログには .d の中身までは残っていない。
# ここは「未確認」と正直に記しておく。
#
# ただし対策は変わらない。どちらの機構であっても
# 「.d を全部消す」ことで両方まとめて解消できるからである。
#
# 【では、なぜ .d が壊れていたのか】
# Makefile 末尾には
#     -include ${OBJS:.o=.d}
# があり、コンパイル時に -MMD -MP で生成された .d が読み込まれる。
# PCH の .d（pch/main-pch.hpp.d）の中身は【絶対パス】である:
#     pch/main-pch.hpp.gch: pch/main-pch.hpp \
#       /home/runner/work/_temp/<UUID>/emsdk-main/upstream/emscripten/
#         cache/sysroot/include/SDL2/SDL.h ...
#
# ここで setup-emsdk（mymindstorm/setup-emsdk@v14）は
# 【ジョブごとにランダムな UUID のディレクトリへ emsdk を展開する】。
# 実際に run 33888888789 の 9 ジョブを調べると全部違った:
#     shard-0: _temp/e7b82ce1-bf6e-493f-a4e9-96802d360006/emsdk-main
#     shard-1: _temp/17ed1ac2-9038-4084-a63c-4026e5685b79/emsdk-main
#     （中略。shard-2〜7 もすべて別 UUID）
#     リンク  : _temp/927d2ddc-82ea-43c1-815f-3915d69bde6a/emsdk-main
#
# したがってリンクジョブから見ると、.d が指す SDL.h などの
# 絶対パスは【存在しない】。make は「前提ファイルが無い」ものを
# 常に「更新が必要」と扱うので、PCH は毎回作り直しになる。
# mtime をどう touch しても、この判定は覆せない。
#
# 【対策】リンク段では .d を削除する。
# .o は既に全部そろっていて、これから作るのはリンク成果物だけである。
# .d の役割は「ソースを編集したとき、どの .o を作り直すか」を
# 知ることであり、リンクしかしない場面では最初から不要である。
# 消しても成果物の正しさには一切影響しない。
#
# 【なぜ「パスを書き換える」ではなく「消す」なのか】
# sed で UUID を差し替える案も考えたが採らなかった:
#   ・UUID は毎回変わるので、書き換え先を実行時に特定する必要がある
#   ・emsdk 内部の構成が変わると静かに壊れる
#   ・そもそも不要な情報なので、消すのが最も単純で壊れにくい
# 「使わない情報を正確に保つ」より「使わない情報を捨てる」ほうが安全である。
#
# 実測の詳細は docs/measurements/FACTS.md の F-25 を参照。
#
# ==================================================================
# 使い方
# ==================================================================
#   cdda のチェックアウト先で
#       ../ci/link.sh <オブジェクト全一覧ファイル>
#
#   前提: 全シャードのアーティファクトが obj/tiles/ 以下に
#         すでに展開されていること。
set -euo pipefail

OBJS_ALL="${1:-}"

if [ -z "$OBJS_ALL" ]; then
    echo "使い方: link.sh <オブジェクト全一覧ファイル>" >&2
    exit 1
fi

if [ ! -f "$OBJS_ALL" ]; then
    echo "ERROR: オブジェクト一覧が見つかりません: $OBJS_ALL" >&2
    exit 1
fi

if [ ! -f Makefile ]; then
    echo "ERROR: CDDA のソースツリー内で実行してください" >&2
    exit 1
fi

SCRIPT_DIR="$( cd "$( dirname "$0" )" && pwd )"
# shellcheck source=./make-args.sh
. "$SCRIPT_DIR/make-args.sh"
# shellcheck source=./progress.sh
. "$SCRIPT_DIR/progress.sh"

link_started_at="$( date +%s )"

echo "=================================================================="
echo "[LINK] リンク開始"
echo "=================================================================="

# ------------------------------------------------------------------
# 手順 1: オブジェクトの完全性検証
# ------------------------------------------------------------------
# 【必須】1 個でも欠けていたらここで止める。
#
# 欠けたまま進むと wasm-ld が未定義シンボルを報告するが、
# その時点ではすでに Binaryen の前段まで時間を使っている。
# さらにエラーメッセージはマングルされた C++ シンボル名なので
# 「どのシャードが失敗したか」を読み取るのが非常に困難である。
#
# ここでファイル名として報告すれば、原因のシャードが即座に分かる。
echo "[LINK] === 手順 1/4: オブジェクトの完全性検証 ==="

total="$( grep -c . "$OBJS_ALL" )"
missing=0
empty=0
missing_list=''

while IFS= read -r obj; do
    [ -n "$obj" ] || continue
    if [ ! -f "$obj" ]; then
        missing=$(( missing + 1 ))
        [ "$(( missing + empty ))" -le 20 ] && missing_list="${missing_list}  [欠落] $obj"$'\n'
    elif [ ! -s "$obj" ]; then
        # サイズ 0 は「作られたが中身が無い」状態。
        # コンパイルが途中で殺された（OOM 等）ときに起きる。
        # 存在チェックだけでは通ってしまうので別に検出する。
        empty=$(( empty + 1 ))
        [ "$(( missing + empty ))" -le 20 ] && missing_list="${missing_list}  [空] $obj"$'\n'
    fi
done < "$OBJS_ALL"

if [ "$missing" -gt 0 ] || [ "$empty" -gt 0 ]; then
    echo "ERROR: オブジェクトが揃っていません（欠落 ${missing} 個 / 空 ${empty} 個 / 全体 ${total} 個）" >&2
    printf '%s' "$missing_list" >&2
    echo "" >&2
    echo "       原因の切り分け:" >&2
    echo "       ・欠落 → 該当シャードのジョブが失敗、または" >&2
    echo "                 アーティファクトのアップロード／展開に失敗した" >&2
    echo "       ・空   → コンパイル中にプロセスが殺された（OOM の可能性）" >&2
    echo "                 該当シャードの並列度を下げるか、シャード数を増やす" >&2
    exit 1
fi

echo "[LINK] OK: ${total} 個すべて存在（サイズ 0 のものも無し）"
echo "[LINK] オブジェクト合計サイズ: $( du -sh "$CDDA_OBJ_DIR" 2>/dev/null | cut -f1 || echo '?' )"

# ------------------------------------------------------------------
# 手順 2: version.h / prefix.h の生成
# ------------------------------------------------------------------
# リンク自体は .h を読まないが、Makefile の依存に
# src/version.h が入っているため、無いと make が
# 「version.h を作るために version ターゲットを実行」し、
# その結果 version.h の mtime が更新されて
# version.cpp の再コンパイルが誘発されうる。
#
# 先に作っておけば内容が同一なので Makefile 側の
# 「変わっていなければ書き換えない」分岐が働き、mtime も動かない。
echo "[LINK] === 手順 2/4: version.h / prefix.h 生成 ==="
make -s version prefix "${CDDA_MAKE_ARGS[@]}"

# ------------------------------------------------------------------
# 手順 3: タイムスタンプの整合
# ------------------------------------------------------------------
echo "[LINK] === 手順 3/4: タイムスタンプの整合 ==="

# ------------------------------------------------------------------
# 3-a: .d（依存ファイル）を捨てる
# ------------------------------------------------------------------
# 【なぜ消すのか】冒頭の長い解説のとおり。
# .d には emsdk の【絶対パス】が焼き込まれているが、
# setup-emsdk はジョブごとに違う UUID のディレクトリへ展開するため、
# リンクジョブから見るとそのパスは存在しない。
# make は「前提ファイルが存在しない」ものを常に古いと見なすので、
# PCH が毎回作り直され、PCH に依存する src/*.o が
# 巻き添えで再コンパイルされる（実測 406 個 / 19 分の損失）。
#
# リンクしかしない場面で .d は不要なので、削除するのが最も安全である。
dep_count=0
if [ -d "$CDDA_OBJ_DIR" ]; then
    dep_count="$( find "$CDDA_OBJ_DIR" -name '*.d' -type f | wc -l )"
    find "$CDDA_OBJ_DIR" -name '*.d' -type f -delete
fi
# PCH の .d も同じ理由で消す。むしろこれが主犯である。
pch_dep_dir="$( dirname "$( make -s print-PCH_P "${CDDA_MAKE_ARGS[@]}" )" )"
if [ -d "$pch_dep_dir" ]; then
    pch_deps="$( find "$pch_dep_dir" -name '*.d' -type f | wc -l )"
    find "$pch_dep_dir" -name '*.d' -type f -delete
    dep_count=$(( dep_count + pch_deps ))
fi
echo "[LINK] .d を ${dep_count} 個削除しました（emsdk の絶対パスが無効なため）"

# PCH が無い場合は作る。
# 【なぜリンクジョブで PCH が必要なのか】
# PCH は .o の依存に入っているので、無いと make は
# 「PCH を作る → その PCH より古い .o を全部作り直す」
# と判断してしまう。存在させるだけで再コンパイルを防げる。
PCH_TARGET="$( make -s print-PCH_P "${CDDA_MAKE_ARGS[@]}" )"
if [ ! -s "$PCH_TARGET" ]; then
    echo "[LINK] PCH が無いので生成します: $PCH_TARGET"
    make "${CDDA_MAKE_ARGS[@]}" "$PCH_TARGET"
    if [ ! -s "$PCH_TARGET" ]; then
        echo "ERROR: PCH の生成に失敗しました: $PCH_TARGET" >&2
        exit 1
    fi
fi

# 【順序が重要】ソース → PCH → .o の順で新しくする。
# 逆順にすると make が再コンパイルを判断してしまう。
#
# ソースには触らない（触ると git の状態が変わり、
# version.h の dirty 判定に影響しうる）。
# PCH と .o を「今」にすれば、checkout 済みソースより
# 新しくなるので十分である。
touch "$PCH_TARGET"
sleep 1
# 1 秒待つ理由: ファイルシステムの mtime 粒度が 1 秒の場合、
# 同一秒内の touch では PCH と .o が同時刻になる。
# make は「同時刻なら再ビルド不要」と扱うのが一般的だが、
# 実装差に賭けたくないので明確に差を付ける。

# xargs でまとめて touch する。440 回 fork するより速い。
tr '\n' '\0' < "$OBJS_ALL" | xargs -0 -r touch
echo "[LINK] PCH と ${total} 個の .o を現在時刻に更新しました"

# 整合できたことの確認: make が「何も作り直す必要が無い」と
# 判断するかを -q（question モード）で問う。
#
# make -q は「更新が必要なら 1、不要なら 0」を返す。
# ターゲット自身（wasm）はまだ無いので 1 が返るのが正常であり、
# ここでは代わりに【個々の .o が最新と見なされるか】を確かめる。
stale=0
stale_list=''
# 全部調べると 440 回 make を呼ぶことになるので、
# 代表として最初の 5 個だけ検査する。
# タイムスタンプ整合は全 .o に一律 touch しているので、
# 標本で十分に判定できる。
sample=0
while IFS= read -r obj; do
    [ -n "$obj" ] || continue
    sample=$(( sample + 1 ))
    [ "$sample" -gt 5 ] && break
    if ! make -q "${CDDA_MAKE_ARGS[@]}" "$obj" 2>/dev/null; then
        stale=$(( stale + 1 ))
        stale_list="${stale_list}  $obj"$'\n'
    fi
done < "$OBJS_ALL"

if [ "$stale" -gt 0 ]; then
    echo "WARNING: 標本 5 個のうち ${stale} 個が「再ビルド必要」と判定されました:" >&2
    printf '%s' "$stale_list" >&2
    echo "         リンク時に再コンパイルが走り、分割の効果が失われます。" >&2
    echo "         タイムスタンプ整合が効いていない可能性があります。" >&2
    # 【失敗にはしない】理由:
    # 再コンパイルされても成果物は正しい。遅くなるだけである。
    # ここで止めるとビルドが完全に通らなくなり、
    # 「遅いが動く」より悪い状態になる。警告に留める。
else
    echo "[LINK] OK: 標本 5 個すべて最新と判定（再コンパイルは発生しません）"
fi

# ------------------------------------------------------------------
# 手順 4: リンク
# ------------------------------------------------------------------
echo "[LINK] === 手順 4/4: リンク（Binaryen/wasm-opt 込み） ==="
echo "[LINK] この工程は【ジョブに分割できません】（大域解析が必要なため）。"
echo "[LINK] ただし wasm-opt 自体はプロセス内でマルチスレッド動作します。"
echo "[LINK] 内訳の目安: wasm-ld で 3〜4 割、post-link（wasm-opt 等）で 6〜7 割。"
echo "[LINK] メモリを 7GB 超使う工程があるため、メモリ表示も併せて出します。"

# ------------------------------------------------------------------
# 進捗表示について（旧実装からの変更点）
# ------------------------------------------------------------------
# 【旧実装の問題】
# 分母を 2（.js と .wasm）にして生成物の実在数を数えていた。
# その結果、実際のログはこうなった:
#
#   [PROGRESS] link (単一スレッド) [------] 0% (0/2) 経過 19m01s
#   [PROGRESS] link (単一スレッド) [###---] 50% (1/2) 経過 19m31s
#      … 以降 40 分以上ずっと 50% のまま …
#
# 40 分のうち 22 分が 1 つの目盛りに押し込まれ、
# 進んでいるのか固まっているのか判別できなかった。
#
# 【新実装】
# emcc の子孫プロセス名を /proc/<pid>/comm から読み、
# 「いま何をしているか」を工程名で出す（F-22-3 で実測確認）。
#
#   wasm-ld → wasm-emscripten-finalize → wasm-opt
#   → acorn-optimizer ×3 → wasm-opt → acorn-optimizer
#
# 分子が動かなくても「wasm-opt を 20 分やっている」と分かる。
# 加えて工程が切り替わった時刻を履歴として残すので、
# 後から「どこで時間を食ったか」を特定できる。
#
# 【想定所要時間】
# 以前は 45 分固定にしていたが、実測 4h02m と 4 倍以上ずれていて
# 「想定超過」を出し続けるだけの無意味な表示になっていた。
# 実測に基づき、最適化レベルごとに分けて既定値を決める:
#
#     -Os : 4h02m（実測）        → 14520s
#     -O2 : 約 3h14m（実測 -20%） → 11640s（← 116 のときの値）
#     -O1 : 約 53 分（実測 -78%） →  3180s
#
# 【さらに Binaryen 132 差し替えぶんを織り込む】
# ci/setup-binaryen.sh が wasm-opt を 116 → 132 に差し替える。
# 132 は inlining-optimizing（リンク時間の 71%）が高速化されており、
# 本番同一引数・N=4000・3 回反復の実測で:
#
#     116 -Os 平均 5.871s → 132 -O2 平均 3.650s = 【-37.8%】
#
# wasm-opt はリンク段の 93% なので、リンク段全体はほぼ同率で縮む:
#
#     -O2 : 242 分 × 0.62 ≒ 約 148 分  →  8880s
#     -O1 : 53 分 相当を据え置き（-O1 は元々インライン反復を
#           回さないので 132 の恩恵が小さい）→ 3180s
#
# 【この値の性質】
# これは「超過したら失敗」の閾値ではなく、進捗率の分母にすぎない。
# 外れても表示が不正確になるだけでビルドは通る。
# 132 の差し替えが失敗して 116 のままだった場合は実際には
# もっとかかるが、その場合 [BINARYEN] の警告がログに出ている。
#
# CDDA_LINK_OPT は ci/tune-makefile.sh と同じ変数である。
# 明示的に CDDA_LINK_EXPECT_SEC が渡されていればそれを尊重する。
if [ -z "${CDDA_LINK_EXPECT_SEC:-}" ]; then
    case "${CDDA_LINK_OPT:-O2}" in
        O1) CDDA_LINK_EXPECT_SEC=3180 ;;
        O2) CDDA_LINK_EXPECT_SEC=8880 ;;
        *)  CDDA_LINK_EXPECT_SEC=14520 ;;
    esac
fi
echo "[LINK] 想定所要: $(( CDDA_LINK_EXPECT_SEC / 60 )) 分（最適化 -${CDDA_LINK_OPT:-O2} の実測に基づく推定）"

link_make_started_at="$( date +%s )"

# make をバックグラウンドで起動し、その PID を監視する。
# 【なぜ make を直接監視できるのか】
# 監視側は子孫を再帰的に辿るので、make → emcc → wasm-opt の
# 3 段下でも検出できる。
make -j"$CDDA_MAKE_JOBS" "${CDDA_MAKE_ARGS[@]}" "$CDDA_TARGET_JS" &
link_make_pid="$!"

progress_link_monitor_start "$link_make_pid" "link" 30 "$CDDA_LINK_EXPECT_SEC"
# 監視は必ず止める。ここで止め損なうとジョブが終わらない。
trap progress_link_monitor_stop EXIT

# make の終了コードを取りこぼさない。
# 【重要】バックグラウンド起動にしたので set -e では拾えない。
# wait の戻り値を明示的に見て、失敗ならここで落とす。
link_rc=0
wait "$link_make_pid" || link_rc="$?"

progress_link_monitor_stop
trap - EXIT

if [ "$link_rc" -ne 0 ]; then
    echo "ERROR: リンクが失敗しました（make の終了コード: ${link_rc}）" >&2
    echo "       メモリ不足（OOM）の可能性があります。直前のメモリ表示を確認してください。" >&2
    exit "$link_rc"
fi

link_elapsed=$(( $( date +%s ) - link_make_started_at ))

# ------------------------------------------------------------------
# 成果物の検証
# ------------------------------------------------------------------
for f in "$CDDA_TARGET_JS" "$CDDA_TARGET_WASM"; do
    if [ ! -s "$f" ]; then
        echo "ERROR: 成果物が生成されていません: $f" >&2
        exit 1
    fi
done

js_size="$( du -h "$CDDA_TARGET_JS" | cut -f1 )"
wasm_size="$( du -h "$CDDA_TARGET_WASM" | cut -f1 )"
wasm_bytes="$( wc -c < "$CDDA_TARGET_WASM" )"
total_elapsed=$(( $( date +%s ) - link_started_at ))

echo "=================================================================="
echo "[LINK] 完了"
echo "[LINK] リンク所要:   $( format_hms "$link_elapsed" )"
echo "[LINK] ジョブ全体:   $( format_hms "$total_elapsed" )"
echo "[LINK] $CDDA_TARGET_JS:   $js_size"
echo "[LINK] $CDDA_TARGET_WASM: $wasm_size"
echo "=================================================================="

# ------------------------------------------------------------------
# 4GB RAM 機で動くかの目安チェック
# ------------------------------------------------------------------
# 【なぜここで見るのか】
# 利用者の要求は「RAM 4GB の PC でも動くこと」である。
# wasm のサイズはそのままブラウザのメモリ消費に効く
# （wasm はコンパイル後のコードもメモリに載る）。
#
# tune-makefile.sh で INITIAL_MEMORY=256MB / MAXIMUM_MEMORY=2GB に
# 絞っているが、wasm 自体が肥大すればその前提が崩れる。
# ビルドのたびに気づける場所に出しておく。
#
# 60MiB を目安にしているのは、
#   ・wasm 本体 + ブラウザのコンパイル済みコード（概ね同程度）
#   ・+ MAXIMUM_MEMORY 2GB の線形メモリ
#   ・+ ブラウザ自身とタブの基礎消費
# を足して 4GB 機の空きに収まる範囲、という見積りである。
wasm_mib=$(( wasm_bytes / 1048576 ))
echo "[LINK] wasm サイズ: ${wasm_mib} MiB"
if [ "$wasm_mib" -gt 60 ]; then
    echo "[LINK] 注意: wasm が ${wasm_mib} MiB あります（目安 60 MiB 超）。"
    echo "[LINK]       4GB RAM 機での読み込みが厳しくなる可能性があります。"
    echo "[LINK]       LDFLAGS の -Os が効いているか確認してください。"
fi

# ------------------------------------------------------------------
# 実行結果ページ（Summary）への要約
# ------------------------------------------------------------------
# ヘッダは自分で書く（ジョブ間で共有されないため。F-22-4）
step_summary_table "リンク" \
    "| link | ${total} 個 | $( format_hms "$link_elapsed" ) | js $js_size / wasm $wasm_size (${wasm_mib} MiB) |"

# リンクは全体の所要時間を支配する工程なので、
# 内訳の目安も残しておく。次回のチューニングの手がかりになる。
step_summary \
    "リンクは【ジョブ分割できない】工程です（Asyncify が大域解析を要するため）。" \
    "ただし \`wasm-opt\` はプロセス内でマルチスレッド動作します（実測 user/real = 1.59）。" \
    "コア数を増やしても大域解析部分が支配的で、ほとんど短縮しません。" \
    ""
