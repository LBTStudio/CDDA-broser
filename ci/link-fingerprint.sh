#!/usr/bin/env bash
# CDDA 0.I ブラウザ版: リンク結果のキャッシュキー（指紋）を計算する
#
# ==================================================================
# なぜこれが必要なのか
# ==================================================================
# 実測（F-23-1）で、ビルド 4 時間 23 分のうち
# **wasm-opt 単独が 4 時間 02 分（93%）** を占めることが分かった。
#
# ここで重要なのは、wasm-opt の入力が
#     「440 個の .o」＋「リンク引数」
# だけであるという点である。この 2 つが前回と完全に同じなら、
# 出力（.js / .wasm）も完全に同じになる。
# つまり **4 時間まるごと省略できる**。
#
# 利用者の主題は「Action が長すぎる。その上で改善もできるように
# してほしい」である。改善サイクルでは
#
#   ・データ（data/, gfx/）だけ直した
#   ・MOD を足した
#   ・HTML / JS ラッパだけ直した
#   ・ワークフローの設定だけ直した
#
# といった「C++ を 1 行も触っていない」変更が頻繁に起きる。
# その場合 .o は全部 ccache から即座に復元され、
# 残るのは 4 時間の wasm-opt だけ、という最悪の形になる。
# これを 0 秒にするのがこのキャッシュの目的である。
#
# ==================================================================
# 指紋に何を入れるか（入れ忘れると「古い wasm を配る」事故になる）
# ==================================================================
# リンク出力を決めるものすべてを入れる必要がある。
#
#   (1) 全 .o の内容           ← C++ の変更が反映される
#   (2) リンク引数（make 変数）← RELEASE / TILES / LOCALIZE など
#   (3) 最適化レベル           ← CDDA_LINK_OPT（O2 / O1）
#   (4) Makefile 自体          ← LDFLAGS の変更が反映される
#   (5) ci/*.sh                ← リンク手順そのものの変更
#   (6) emsdk のバージョン     ← Binaryen が変われば出力も変わる
#
# 【(1) をファイル名ではなく内容で取る理由】
# ファイル名・個数だけでは、同じ名前で中身が変わった場合
# （＝ C++ を編集した通常のケース）を検出できない。
# 内容のハッシュを取らないと意味がない。
#
# 【(1) をソートする理由】
# find の返す順序はファイルシステム依存で、同じ内容でも
# 実行ごとに変わりうる。ソートしないと毎回キーが変わり、
# キャッシュが一度も当たらない。
#
# 【安全側の設計】
# 入れ忘れがあると「変更したのに古い wasm が配られる」という
# 最も気づきにくい事故になる。逆に余計なものを入れた場合は
# 「当たるべきキャッシュが当たらない」だけで、正しさは壊れない。
# よって迷ったら入れる。上記 (4)(5) は厳密には過剰だが、
# 過剰な側に倒してある。
# ==================================================================

set -euo pipefail

objs_list="${1:-}"

if [ -z "$objs_list" ] || [ ! -f "$objs_list" ]; then
    echo "usage: link-fingerprint.sh <objs-all.txt>" >&2
    exit 1
fi

script_dir="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"

# ------------------------------------------------------------------
# (1) 全 .o の内容ハッシュ
# ------------------------------------------------------------------
# 【なぜ objs-all.txt を基準にするのか】
# find obj -name '*.o' だと、前回の実行で残った無関係な .o や
# 一時ファイルを拾いうる。shard-plan.sh が Makefile から
# 生成した正規の一覧を基準にすれば、対象が厳密に確定する。
#
# 【先に完全性を見る理由】
# .o が欠けたまま指紋を出すと、その「欠けた状態の指紋」で
# キャッシュを保存してしまい、次回それに当たって
# 不完全な wasm を配る危険がある。数が合わない時点で
# 指紋を無効化し、必ずリンクを走らせる。
# 【pipefail の罠】
# set -o pipefail が有効なので、パイプの途中が非 0 で終わると
# コマンド置換ごと失敗して set -e でスクリプトが死ぬ。
#     while ...; do [ -f "$o" ] && echo x; done | wc -l
# は「最後の .o が存在しない」場合に while が 1 を返すため、
# まさにこの経路で無言死する（実際にこれを踏んだ）。
# ループの終了状態を必ず 0 にするため if 文に書き換える。
obj_count="$( grep -c . "$objs_list" || true )"
found_count="$(
    while IFS= read -r o; do
        [ -n "$o" ] || continue
        if [ -f "$o" ]; then
            echo x
        fi
    done < "$objs_list" | wc -l
)"

if [ "$obj_count" -eq 0 ] || [ "$found_count" -ne "$obj_count" ]; then
    echo "WARN: .o が ${found_count}/${obj_count} 個しかありません。" >&2
    echo "      指紋を無効化します（キャッシュを当てずに必ずリンクします）。" >&2
    # 毎回違う値を返すのでキャッシュには当たらない。
    echo "incomplete-$( date +%s )"
    exit 0
fi

# ここに来た時点で全 .o が実在する。
# sort でファイルシステム依存の順序を消し、
# sha256sum の出力（ハッシュ + ファイル名）をさらに畳む。
# ファイル名も含まれるので「名前が変わった」変更も検出される。
obj_hash="$(
    sort "$objs_list" | tr '\n' '\0' \
        | xargs -0 sha256sum | sha256sum | cut -d' ' -f1
)"

# ------------------------------------------------------------------
# (2)(3) リンク引数と最適化レベル
# ------------------------------------------------------------------
# make-args.sh は CDDA_MAKE_ARGS を定義する単一の情報源である。
# ここを読めば「どんな引数でリンクするか」が確定する。
# shellcheck source=/dev/null
source "${script_dir}/make-args.sh"

args_hash="$(
    {
        printf '%s\n' "${CDDA_MAKE_ARGS[@]}"
        echo "CDDA_LINK_OPT=${CDDA_LINK_OPT:-O2}"
    } | sha256sum | cut -d' ' -f1
)"

# ------------------------------------------------------------------
# (4)(5) Makefile と CI スクリプト
# ------------------------------------------------------------------
env_hash="$(
    {
        [ -f Makefile ] && sha256sum Makefile
        cat "${script_dir}"/*.sh 2>/dev/null | sha256sum
        # (6) emsdk のバージョン。Binaryen が変われば出力が変わる。
        # emcc が使えない環境（指紋計算だけを試すとき）でも
        # 落ちないように失敗を許容する。
        emcc --version 2>/dev/null | head -1 || echo "emcc-unknown"

        # (7) wasm-opt（Binaryen）の版【emcc の版とは独立に変わる】
        #
        # ci/setup-binaryen.sh が wasm-opt だけを 116 → 132 に
        # 差し替えるので、emcc の版が同じままでも
        # 【生成される wasm は変わる】。
        #
        # ここを含めないと次の事故が起きる:
        #   ・132 で作った成果物のキャッシュを、差し替えが失敗して
        #     116 になった実行が「同じ指紋」と見なして再利用する
        #   ・逆に 116 時代の古いキャッシュを 132 の実行が掴む
        # どちらも「意図した版で作られていない成果物を配布する」
        # ことになるので、版そのものを指紋に入れる。
        #
        # 【なぜ setup-binaryen.sh のハッシュでは不十分か】
        # 上の cat "${script_dir}"/*.sh に setup-binaryen.sh が
        # 含まれるので、スクリプトを編集して版を上げた場合は
        # 指紋が変わる。しかし CDDA_BINARYEN_VERSION 環境変数で
        # 上書きした場合や、差し替えが失敗して 116 のままだった
        # 場合はスクリプトの内容が変わらないため検出できない。
        # 実際に動く wasm-opt を直接聞くのが唯一確実な方法である。
        if [ -n "${EMSDK:-}" ] && [ -x "$EMSDK/upstream/bin/wasm-opt" ]; then
            "$EMSDK/upstream/bin/wasm-opt" --version 2>/dev/null | head -1
        elif command -v wasm-opt >/dev/null 2>&1; then
            wasm-opt --version 2>/dev/null | head -1
        else
            echo "wasm-opt-unknown"
        fi
    } | sha256sum | cut -d' ' -f1
)"

# ------------------------------------------------------------------
# 最終的な指紋
# ------------------------------------------------------------------
# 16 文字に切るのは、GitHub Actions のキャッシュキーが
# 512 文字までという制限に対して余裕を持たせるため。
# 16 進 16 文字 = 64bit なので、現実的な回数の衝突は起きない。
printf '%s%s%s' "$obj_hash" "$args_hash" "$env_hash" \
    | sha256sum | cut -c1-16
